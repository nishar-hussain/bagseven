const providerUrl = process.env.DEMO_PROVIDER_URL ?? `http://127.0.0.1:${process.env.DEMO_PROVIDER_PORT ?? 4007}`;
const policyUrl = process.env.POLICY_URL ?? 'http://127.0.0.1:4003';
const adminToken = process.env.PROVIDER_ADMIN_TOKEN;
if (!adminToken) throw new Error('PROVIDER_ADMIN_TOKEN is required to register the demo provider');
const health = await fetch(`${providerUrl}/healthz`);
if (!health.ok) throw new Error(`Demo provider is not reachable at ${providerUrl}`);
const { address } = await health.json() as { address: string };
const hostname = new URL(process.env.DEMO_AGENT_PROVIDER_URL ?? `${providerUrl}/weather`).hostname;
const response = await fetch(`${policyUrl}/v1/providers`, { method: 'POST', headers: { authorization: `Bearer ${adminToken}`, 'content-type': 'application/json' }, body: JSON.stringify({ hostname, address }) });
const payload = await response.json();
if (!response.ok) throw new Error(JSON.stringify(payload));
console.log(JSON.stringify({ registered: true, hostname, address, provider: payload }, null, 2));
